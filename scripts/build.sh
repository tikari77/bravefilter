#!/bin/bash
# フィルタリストを生成する
#   src/*.txt          → dist/filters.txt  （メインのリスト）
#   src/<name>/*.txt   → dist/<name>.txt   （別リスト。Brave で個別に購読できる）
# 各リストは 00-header.txt を先頭に、残りを名前順に結合する
set -euo pipefail
cd "$(dirname "$0")/.."
version=$(git log -1 --format=%cd --date=format:%Y%m%d%H%M 2>/dev/null || date +%Y%m%d%H%M)

build() { # build <srcdir> <out>
  local dir=$1 out=$2 tmp
  tmp=$(mktemp)
  {
    cat "$dir/00-header.txt"
    echo "! Version: $version"
    for f in "$dir"/*.txt; do
      [ "$(basename "$f")" = 00-header.txt ] && continue
      echo
      echo "! --- $(basename "$f") ---"
      # 行末空白と CR を除去
      sed -e 's/\r$//' -e 's/[[:space:]]*$//' "$f"
    done
    # gen.sh があればその出力（リストから生成したルール）も追加
    if [ -x "$dir/gen.sh" ]; then
      echo
      echo "! --- generated by gen.sh ---"
      "$dir/gen.sh"
    fi
  } > "$tmp"
  # 重複ルール警告（コメント・空行除く）
  local dups
  dups=$(grep -v -e '^!' -e '^$' "$tmp" | LC_ALL=C sort | LC_ALL=C uniq -d || true)
  [ -n "$dups" ] && { echo "⚠️ $out に重複ルール:"; echo "$dups"; } >&2
  mv "$tmp" "$out"
  echo "built $out ($(grep -cv -e '^!' -e '^$' "$out" || true) rules)"
}

build src dist/filters.txt
for d in src/*/; do
  d=${d%/}
  [ -f "$d/00-header.txt" ] || { echo "skip $d (00-header.txt なし)" >&2; continue; }
  build "$d" "dist/$(basename "$d").txt"
done
